-- Query 2: Students per institution

SELECT
    i.name AS institution,
    COUNT(s.student_id) AS total_students
FROM institutions i
LEFT JOIN students s
ON i.institution_id = s.institution_id
GROUP BY i.institution_id, i.name;

-- Query 3: Enrolments per course

SELECT
    c.course_name,
    COUNT(e.enrollment_id) AS total_enrollments
FROM courses c
LEFT JOIN enrollments e
ON c.institution_id = e.institution_id
AND c.course_id = e.course_id
GROUP BY c.course_id, c.course_name;

-- Query 4: Attendance report

SELECT
    c.course_name,
    a.status,
    COUNT(*) AS attendance_count
FROM attendance_records a
JOIN enrollments e
ON a.institution_id = e.institution_id
AND a.enrollment_id = e.enrollment_id
JOIN courses c
ON e.institution_id = c.institution_id
AND e.course_id = c.course_id
GROUP BY c.course_name, a.status
ORDER BY c.course_name;

-- Query 5: Students without enrolments

SELECT
    s.student_id,
    s.full_name,
    s.email
FROM students s
LEFT JOIN enrollments e
ON s.institution_id = e.institution_id
AND s.student_id = e.student_id
WHERE e.enrollment_id IS NULL;

-- Query 6: Audit history

SELECT *
FROM audit_logs
ORDER BY created_at DESC;

