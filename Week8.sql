CREATE TABLE institutions (
    institution_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE app_users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id INT NOT NULL REFERENCES institutions(institution_id),
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(30) NOT NULL
        CHECK (role IN ('admin', 'teacher', 'student')),
    UNIQUE (institution_id, email),
    UNIQUE (institution_id, user_id)
);

CREATE TABLE students (
    student_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id INT NOT NULL REFERENCES institutions(institution_id),
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone VARCHAR(30),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (institution_id, email),
    UNIQUE (institution_id, student_id)
);

CREATE TABLE courses (
    course_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id INT NOT NULL REFERENCES institutions(institution_id),
    course_name VARCHAR(150) NOT NULL,
    description TEXT,
    duration_weeks INT CHECK (duration_weeks > 0),
    UNIQUE (institution_id, course_name),
    UNIQUE (institution_id, course_id)
);

CREATE TABLE enrollments (
    enrollment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id INT NOT NULL,
    student_id INT NOT NULL,
    course_id INT NOT NULL,
    enrollment_date DATE DEFAULT CURRENT_DATE,
    status VARCHAR(30) DEFAULT 'active'
        CHECK (status IN ('active', 'completed', 'withdrawn')),
    FOREIGN KEY (institution_id, student_id)
        REFERENCES students(institution_id, student_id),
    FOREIGN KEY (institution_id, course_id)
        REFERENCES courses(institution_id, course_id),
    UNIQUE (institution_id, student_id, course_id),
    UNIQUE (institution_id, enrollment_id)
);

CREATE TABLE attendance_records (
    attendance_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id INT NOT NULL,
    enrollment_id INT NOT NULL,
    attendance_date DATE DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('present', 'absent', 'late')),
    FOREIGN KEY (institution_id, enrollment_id)
        REFERENCES enrollments(institution_id, enrollment_id),
    UNIQUE (enrollment_id, attendance_date)
);

