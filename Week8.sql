-- Query 1: Recent student enrolments

EXPLAIN (ANALYZE, BUFFERS)
SELECT
    enrollment_id,
    student_id,
    course_id,
    enrollment_date,
    status
FROM enrollments
WHERE institution_id = 1
AND enrollment_date >= CURRENT_DATE - INTERVAL '30 days'
ORDER BY enrollment_date DESC;

-- Optimization index

CREATE INDEX IF NOT EXISTS idx_enrollments_date
ON enrollments(institution_id, enrollment_date);

ANALYZE enrollments;

