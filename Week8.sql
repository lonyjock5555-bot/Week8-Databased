BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_roles WHERE rolname = 'app_read'
    ) THEN
        CREATE ROLE app_read;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_roles WHERE rolname = 'app_write'
    ) THEN
        CREATE ROLE app_write;
    END IF;
END
$$;

