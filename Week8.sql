CREATE TABLE audit_logs (
    audit_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    institution_id INT NOT NULL REFERENCES institutions(institution_id),
    table_name TEXT NOT NULL,
    operation TEXT NOT NULL,
    old_data JSONB,
    new_data JSONB,
    changed_by TEXT DEFAULT CURRENT_USER,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX idx_audit_institution_date
ON audit_logs(institution_id, created_at DESC);

CREATE OR REPLACE FUNCTION record_audit()
RETURNS TRIGGER AS $$
DECLARE
    old_record JSONB;
    new_record JSONB;
    tenant_id INT;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        old_record := TO_JSONB(OLD);
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        new_record := TO_JSONB(NEW);
    END IF;

    tenant_id := COALESCE(
        (new_record->>'institution_id')::INT,
        (old_record->>'institution_id')::INT
    );

    INSERT INTO audit_logs (
        institution_id, table_name, operation,
        old_data, new_data
    )
    VALUES (
        tenant_id, TG_TABLE_NAME, TG_OP,
        old_record, new_record
    );

    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_students_audit
AFTER INSERT OR UPDATE OR DELETE ON students
FOR EACH ROW EXECUTE FUNCTION record_audit();

CREATE TRIGGER trg_courses_audit
AFTER INSERT OR UPDATE OR DELETE ON courses
FOR EACH ROW EXECUTE FUNCTION record_audit();

CREATE TRIGGER trg_enrollments_audit
AFTER INSERT OR UPDATE OR DELETE ON enrollments
FOR EACH ROW EXECUTE FUNCTION record_audit();

CREATE TRIGGER trg_attendance_audit
AFTER INSERT OR UPDATE OR DELETE ON attendance_records
FOR EACH ROW EXECUTE FUNCTION record_audit();

